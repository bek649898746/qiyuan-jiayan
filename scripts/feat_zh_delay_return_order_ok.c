/* D-11e-D4 (2026-10-01 虾米 · 第 439 站续十三): **返回路径求值顺序 根治**（本仓新挖出的【通用】缺陷）。
   ── 病灶: `号寅(结)`（返回路径包装器 L7834）**两分支都把 `接子(单回, 结)` 放在最后** ⟹ 延迟/析构
      **先于** 返回表达式求值 ⟹ `整 f(){ 延迟 g=99; 返 g; }` 返回 **99**（应 0 —— 延迟应在返回之后）。
      影响面 = **所有 `延迟` 用户**（尤其 `锁住`/`使用`/`放行` 类资源释放 ⟹ 会在求值前就释放）。
   ── 根因（插桩定案）: `结` 是**返回节**（`建节(6)`，L12066 `整 结 = 建节(6); … 接子(结, 左戊);`），
      **不是普通表达式**。上一刃把它塞进「声明节」当初始化值 ⟹ **返节的码生成直接发出 `ret`**
      ⟹ 函数在延迟之前就返回（值却正确，因为 `ret` 时 rax 恰是表达式值）⟹ 延迟/后续节点全不执行。
   ── 修法（两处）: ① 求值用 **`子0[结]`**（真返回表达式）而非 `结` 自身；
      ② 块尾放 **新建的返节**（`建节(6)` + 子0 = 临时变量）⟹ 先求值、后延迟、再以临时为返回值。
   ── 灵敏度: 改前编译器（`E1F35ABB`）本锚输出 **99** ⟹ 与 @EXPECTED 不符 ⟹ **必红**。 */
整 g = 0;
整 f(空) {
    延迟 g = 99;              /* 必须在 返回表达式 求值 **之后** 执行 */
    返 g;
}
