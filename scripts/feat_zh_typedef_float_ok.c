#include <stdio.h>

/* R238 补锚 — **typedef float 别名**的变量与数组（单精度语义）
 *
 * 病根族（与 R236 同）：`当丙`（double 语义）的赋值点共 6 处，`单丙`（float 语义）仅若干处。
 *   其中两处 **typedef 路径**只看 `型定表[X].是否浮标` —— 而 **float 与 double 都是"浮标"**
 *   ⟹ `typedef float F;` 的声明落到 `当丙 = 1`（当双精度）而 `单丙 = 0` ⟹ 元素/宽度按 8 字节算。
 *   实测（`r9/r238a.c`）：`F 单数组[2]` 的 `单数组[0]` 读出 `0.00`（应 3.50）。
 *   R238 在两条 typedef 路径各补 `若 (型定表[X].尺寸 == 4) 单丙 = 1;`（浮点族里尺寸 4 ⟺ float）。
 *
 * 本锚钉已修形态（局部/静态标量 + **数组元素**）：
 *   ① 局部 `F` 标量   ② 文件级 static `F` 标量   ③ `F` 数组元素 [0] ④ [1]
 * ✅ **R239 已修（含在本锚内）**：`F *p; p[i]`（typedef float 的**指针解引用**）原「**步长 8、载荷 4**」
 *   （块内实测 `p[1]` 取到 `a[2]` = 5.500000）—— 根因是 R238 只加 `单丙` 却**保留 `当丙`**；
 *   R239 改为 `若 (尺寸 == 4) { 单丙 = 1; 当丙 = 0; }`（`当丙`(double) 与 `单丙`(float) **互斥**）。
 *   ⚠️ 早期版本的本注释曾写「与 `static double **dpp` 同族 / 按 32 位读」——**那是错的**（已被 R239 实测推翻）。
 * ⏳ **仍未修（不在本锚内）**：**文件级** `typedef float` 数组（`static F g[N]`）——
 *   第三条声明路径（R238/R239 只覆盖块内），根因 = 文件级 `单回` 未随之置位；见 R242。
 */

typedef float  单别名;
typedef double 双别名;

static 单别名 静单 = 1.5f;
static 双别名 静双 = 2.25;

int main(void) {
    单别名 局单 = 1.5f;
    双别名 局双 = 2.25;
    单别名 单数组[4];
    单别名 *单指针;
    双别名 *双指针;
    双别名 双数组[4];

    单数组[0] = 3.5f;
    单数组[1] = 4.5f;
    单数组[2] = 5.5f;
    单数组[3] = 6.5f;
    双数组[0] = 1.25;
    双数组[1] = 2.25;

    单指针 = 单数组;
    双指针 = 双数组;

    if ((double)局单 != 1.5)  return 1;   /* ① 局部标量 */
    if ((double)静单 != 1.5)  return 2;   /* ② 文件级 static 标量 */
    if ((double)单数组[0] != 3.5) return 3;  /* ③ ← R238 靶心（改前 0.00） */
    if ((double)单数组[1] != 4.5) return 4;  /* ④ */
    if ((double)单指针[1] != 4.5) return 6;  /* ⑥ ← R239 靶心（改前 5.50 = 步长 8 取到 [2]） */
    if ((double)单指针[3] != 6.5) return 7;  /* ⑦ */
    if (局双 != 2.25 || 静双 != 2.25) return 5;      /* 双精度标量 对照 */
    if (双指针[1] != 2.25) return 8;                 /* 双精度指针 对照 */

    printf("PASS\n");
    return 0;
}
