/* A3 (2026-09-11): 闭包 数组 (编译期 常量下标) — 闭包 是 解析期 展开 的 句柄 (无 运行时 闭包值),
   故 `闭包 gs[N];` + `gs[k] = 函 捕获 …(v);` 在 解析期 把 槽 k 登记 为 具名 闭包 "gs[k]",
   调用 gs[k](...) 与 具名 闭包 同一 通道 展开 (捕获快照 + 实参)。
   覆盖: 整 捕获 / 多方法 构值 捕获 / 双槽 并存 / 互不污染 / 非数组 回归。 */
