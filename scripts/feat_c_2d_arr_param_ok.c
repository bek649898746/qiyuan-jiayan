/* A71-续8 (2026-09-15): 二维数组作函数参数 —— 族 A 根治锚。
   病灶: 形参解析里数组声明符的维度是 `循环 (...) { ... } /* 跳过 [N] *​/` ——
         **只 词位++ 跳过, 从不登记行宽** ⟹ `整数 a[][3]` 退化后只知元素 4B、不知每行 12B
         ⟹ `a[i][j]` 的行偏移按元素尺寸算 → 地址错 (实测 g(m,0,2) 得 0 应 3 / g(m,1,0) 得 2 应 4);
         且 `指深/指内` 只在「显式 乘 形式」(`若 (指深一 > 0)`) 里设, 数组形参声明里无 `乘`
         ⟹ 内层下标 [c] 步长也错。
         **局部** `整数 (*p)[3] = m; p[1][0]` 本来正确 ⟹ 不是下标语义错, 是「参数衰减后行宽/层级信息丢失」。
   根治: 跳过 `[N]` 时收集各维; 若维数 >= 2 → 行宽 = 元素尺寸 × 形维[1] × 形维[2] … (第一维被参数退化吃掉)
         写 `数组元素尺寸`; 并登记 `指深 = 1 / 指内 = 元素尺寸` (等价于 `整数 (*a)[N]` 的登记)。
   本锚钉: 传参取值 / 全数组求和 / 不同行宽 (行宽 3 与 2) 三形态, 与 gcc 逐字节一致。
   ⚠️ 未覆盖 (挂账): `整数 (*a)[3]` 写法走**另一条解析路径**, 本次未修。 */
#include <stdio.h>

int g(int a[][3], int r, int c) { return a[r][c]; }
int sum(int a[][3], int rows) { int i, j, s = 0; for (i = 0; i < rows; i++) for (j = 0; j < 3; j++) s += a[i][j]; return s; }
int col(int a[][2], int r) { return a[r][0]; }

int main(void) {
    int m[2][3] = {{1,2,3},{4,5,6}};
    int n[2][2] = {{1,2},{3,4}};
    printf("A=%d%d%d%d B=%d C=%d\n", g(m,0,0), g(m,0,2), g(m,1,0), g(m,1,2), sum(m,2), col(n,1));
    return 0;
}
