/* feat_c_ptr_to_array_ok.c — 指针到数组 下标/解引用 (A71 第2项 根治 2026-09-15)
   病灶: `int (*名)[N]` 声明器 被误判 函数指针 `(*f)(...)` (只看 `(` `*`, 不区分 `)` 后是 `(` 还是 `[`)
         → pm 注册 指深=0/指元素=4/数组元素=8 → pm[i] 步长 8 非 12 且 结果数组未传递元素宽 → 0xC0000005.
   修法: ① 声明器 补「指针-到-数组」注册 (指深=1/指元素=总尺寸/域行数链);
         ② 解引用 节点 对 指针-到-数组 衰减取址 (不加载) 且 长卯=域行数[0];
         ③ 嵌套基 补「深乙==0 但 根指内>0」时 长卯=内重 (下标结果数组元素宽).
   本锚: (*pm)[1][2] 二维 + (*pa)[2] 一维, 与 gcc 一致. */
// @EXPECTED out:x=6 y=30
// @EXPECTED exit:0
#include <stdio.h>

int main(void)
{
    int m[2][3] = {{1,2,3},{4,5,6}};
    int (*pm)[2][3] = &m;
    int a[3] = {10,20,30};
    int (*pa)[3] = &a;
    printf("x=%d y=%d\n", (*pm)[1][2], (*pa)[2]);
    return 0;
}
