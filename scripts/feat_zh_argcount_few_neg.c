/* C11 负例锚 (2026-09-24 启元 · 第 300 站): 函数调用 **实参个数不足** 必须响亮报错.
   病灶: 甲言 原 **不校验实参个数** —— `f(1,2)` 对 三参原型 静默取栈垃圾
   (实测 A=4370867) 且 exit=0; gcc 报 `error: too few arguments to function 'f'`.
   修: 调用点 比较 实参数 与 `度伍[己序].参数数`, 不等则 发错误("A9007").
   豁免: 变参函数 (`变参取(名) >= 0` -- printf/scanf) · 闭包调用 (`净挂 >= 0`)
         · 命名实参 (`副双[] >= 0`) · 函数指针调用 (节型别 != 节点_变量)
         · 未登记签名 (`存陆 < 0`) · 第三方 C 语料 (`!序集` 或 `宽松转换`).
   灵敏度: 修前 (CFFD783E) 本锚 **编译成功** ⟹ 框架 判 compile_fail 失败 ⟹ 必红. */
#include <stdio.h>
int f(int a, int b, int c) { return a + b + c; }
int main(void) { printf("A=%d\n", f(1, 2)); return 0; }