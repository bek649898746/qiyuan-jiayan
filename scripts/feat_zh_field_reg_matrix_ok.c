#include <stdio.h>

/* R234 (T5) 补锚 — **结构体字段登记「形态矩阵」（漏登矩阵锚）**
 *
 * 背景（台账 2026-09-12 补登③ · 第 1 刀「字段登记 单点收口」）：
 *   `字段登记(构序,函,域尺寸,行,构型序,对齐依)` = `字段尺寸递归(...)` + `若(构型序!=-1) 字段类型(...)`
 *   —— 把「尺寸登记」与「类型序(毛利)登记」这对**永远成对**的动作收进一处，
 *   使「漏登记 结构体类型序」在结构上不可能。当时只转换了 ③typedef / ④文件级匿名 两块共 6 处，
 *   **其余 `字段尺寸递归` 调用点未收口**（T5 挂账）—— 普查实测：31 个调用点，17 处"孤立"，
 *   其中多数是设计使然（合成字段 / 指针字段 / 联合分支），**台账提示的 L16749/L16857/L16892 已不在列**。
 *
 * 本锚的作用：不靠"数调用点"，而是**用行为照缺陷** —— 每种字段形态都做**二级访问**
 *   （`.字段.内层字段` / `->字段.内层字段` / `数组[i].字段.内层字段`）；
 *   只要某形态的「字段类型序(毛利)」漏登或登错，二级解析必然断链 ⟹ 读到错值 / 崩。
 *
 * 覆盖形态：
 *   ① 标量  ② 结构体**值**字段  ④ 结构体**数组**字段  ⑤ **指针数组**字段
 *   ⑥ **逗号续行**标量  ⑦ **嵌套内联匿名（带字段名）**  ⑧ 内联匿名**指针**
 *   ⑨ 联合成员  ⑩ **逗号续行结构体值**  ⑪ 位域  ⑫ 函数指针字段
 *
 * ⚠️ 两点刻意设计（均为规避/记录**另一个**已知缺陷，非本锚的验证目标）：
 *   1. `struct Outer o = { 0 };` —— 声明即零初始化。裸 `struct Outer o;` + 逐字段赋值会**误触
 *      A4001 未初始化检查**（见挂账 `_DEBT_LEDGER.md` · R234-A4001）：那是一个**独立**缺陷
 *      （写「结构体值字段的内层字段」触发「整体粗粒度 → 字段级精细」降级，降级后读内层字段
 *      按**外层字段完整性**判定 ⟹ 误报未初始化）；机理复杂、触发面宽，**专项站**处理。
 *   2. 二级访问处把内层**两个**字段都写全（`leaf.a` + `leaf.b`），同样是为避开上述误报。
 */

struct Leaf { int a; char b; };                       /* 尺寸 8 */
struct Outer {
    int n;                                       /* ① 标量 */
    struct Leaf leaf;                            /* ② 值字段 */
    struct Leaf arr[2];                          /* ④ 数组字段 */
    struct Leaf *parr[2];                        /* ⑤ 指针数组字段 */
    int m, k;                                    /* ⑥ 逗号续行标量 */
    struct Leaf x, y;                            /* ⑩ 逗号续行结构体值 */
    struct { int u; struct Leaf lf; } anon;      /* ⑦ 内联匿名（带字段名） */
    struct { int v; } *panon;                    /* ⑧ 内联匿名指针 */
    unsigned bw : 3;                             /* ⑪ 位域 */
    int (*fp)(int);                              /* ⑫ 函数指针 */
};

union U { int i; struct Leaf l; };                 /* ⑨ 联合成员 */

static int 加一(int v) { return v + 1; }

int main(void) {
    struct Outer o = { 0 };
    union U u;
    struct Leaf *pp;

    o.n = 1;                                       /* ① */
    o.leaf.a = 2;   o.leaf.b = 3;                  /* ② 二级 */
    o.arr[0].a = 4;                                /* ④ 二级 */
    o.parr[0] = &o.leaf; o.parr[1] = 0;            /* ⑤ */
    o.m = 6; o.k = 7;                              /* ⑥ */
    o.x.a = 8; o.x.b = 1; o.y.a = 9; o.y.b = 2;    /* ⑩ */
    o.anon.u = 10; o.anon.lf.a = 11; o.anon.lf.b = 3;  /* ⑦ 二级 */
    o.bw = 5;                                      /* ⑪ */
    o.fp = 加一;                                   /* ⑫ */

    if (o.n != 1) return 1;                        /* ① */
    if (o.leaf.a != 2 || o.leaf.b != 3) return 2;  /* ② */
    if (o.arr[0].a != 4) return 4;                 /* ④ */
    if (o.parr[0]->a != 2) return 5;               /* ⑤ 经指针数组二级 */
    if (o.m != 6 || o.k != 7) return 6;            /* ⑥ */
    if (o.anon.u != 10 || o.anon.lf.a != 11) return 7;  /* ⑦ 二级（匿名体内层） */
    if (o.bw != 5) return 8;                       /* ⑪ */
    if (o.fp(41) != 42) return 9;                  /* ⑫ */
    if (o.x.a != 8 || o.y.a != 9) return 10;       /* ⑩ */

    pp = &o.leaf;
    if (pp->a != 2) return 11;                     /* 局部结构体指针副本 → 二级 */

    u.l.a = 12;                                    /* ⑨ */
    if (u.l.a != 12) return 12;

    o.panon = 0;                                   /* ⑧ 指针形态读回 */
    if (o.panon != 0) return 13;

    printf("PASS\n");
    return 0;
}
