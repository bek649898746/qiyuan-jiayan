#include <stdio.h>

/* 族1 #6 引用计数（Rc）—— 负例 (2026-10-02 第 444 站):
   引用计数对象被 `取` 消费（所有权移动）后再用 → **A3101 所有权错误: 变量 'r' 已被移动**。
   区分性: 该拒绝由**编译器所有权检查与 Rc 运行时协同**产生 —— 若 Rc 只是无类型标记的自由函数，
           编译器不会把 `取(r)` 登记为移动 ⟹ 静默通过。
   ⚠️ 触发前提（本轮实测）: 变量须用**中文类型名**声明（`整 *p` / `struct Rc r`），
      英文 `int *p` 形态不进入该移动登记路径（实测 rc=0）—— 属已知口径，非本锚弱点。
   正例面见 feat_zh_rc6_ok.c */
int main(void) {
    整 v = 7;
    struct Rc r = 共享(&v, 4);
    整 *p = 取(r);           /* r 被消费（移动） */
    释放(r);                 /* ← A3101: r 已移动, 不能再用 */
    printf("%d\n", *p);
    return 0;
}
