#include <stdio.h>

typedef struct { double *p; int n; } TS;

static double g[3] = {1.5, 2.5, 3.5};
static double *gp = g;
static int gi[3] = {7, 8, 9};
static int *ip = gi;

int main(void) {
    TS s;
    s.p = gp;              /* ① 指针 字段 赋值 (值语义: 不得 当 双精度 转换) */
    s.p[1] = 99.5;         /* ② 成员 指针 字段 下标 写 */
    double a = s.p[1];     /* ③ 成员 指针 字段 下标 读 → 变量 (须 设 浮标) */
    double b = s.p[0];
    s.n = 7;               /* ④ 同结构体 的 整数 字段 (对照) */

    struct TL { double *q; };
    struct TL t;
    t.q = gp;
    t.q[2] = 7.25;         /* ⑤ 局部 类型定义 的 指针 字段 下标 写 */

    struct TI { int *r; };
    struct TI u;
    u.r = ip;
    int c = u.r[1];        /* ⑥ 整数 指针 字段 下标 (对照: 不得 误伤) */

    printf("SPF %.2f %.2f %.2f %d %d %d\n", a, b, g[2], s.n, c, (int)(s.p - g));
    return 0;
}
