// @EXPECTED out:PB2 10 6 2 0 8 0 15 7
// @EXPECTED exit:0
#include <stdio.h>
/* ORD-28 bug2 锚（2026-10-28 · 启元）: **位运算 & ^ | 的优先级**。
   修前（389996FC 及之前）递归链是 移位 → 宽捌(&) → 深序(^) → 余巳(|) → 比较 ⟹ 位运算比比较**更深 = 优先级更高**，
   8 条用例里 6 条与 gcc 不符（2000 轮压测 B 组一致率仅 2.40%）。
   修后链: 移位 → 比较 → 宽捌(&) → 深序(^) → 余巳(|) → 逻辑与。
   灵敏度: 修前本锚输出 `PB2 0 13 2 0 8 0 15 7` 必红（前两条错）。gcc 逐值同。 */
int main(void) {
    int a = 10, b = 4, c = 9, d = 13;
    printf("PB2 %d %d %d %d %d %d %d %d\n",
           a * c < b ^ a,            /* (90<4)^10 = 10  (修前 0) */
           b | d >> (b < c & 7),     /* 4|(13>>1)  = 6   (修前 13) */
           a & 3 + 4,
           5 >= a > 7 & c,
           c ^ d & c * c,
           c <= d <= d > 9,
           a | b ^ c & d,
           (a | b) ^ c & d);
    return 0;
}
