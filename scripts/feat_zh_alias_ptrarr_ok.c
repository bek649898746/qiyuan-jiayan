/* R16 看护锚 —— **typedef 别名 作 数组元素类型**（第 84 站建锚时发现 · 拖 170 站）
   ----------------------------------------------------------------------
   病灶（R16 刀1/刀2 根治）:
     `typedef struct s1 { struct s1 *x, *y; int v; } S;`
     `typedef S *SP;`              ← SP = 「指向 S 的指针」的别名
     `static SP 组八[2];`          ← 用【别名】声明的指针数组
     `组八[0] = &a;  组八[0]->y->v` ← 崩 / 错值

     缺口 = 「别名」这一步（对照 `static S *组十一[2]` 本来正确）:
       ① **全局/静态**（刀1）: 文件级数组登记用 `满转`（= 声明中 `*` 的个数）判「结构体指针数组」;
          `SP 组八[2]` 声明里 **无 `*`** ⟹ `满转 = 0` ⟹ 落「结构体**值**数组」分支（元素 = 尺寸(S) = 24）
          ⟹ 元素槽宽度错 ⟹ 全局静态位移算错 **直接崩 0xC0000005**（局部走帧路径则**静默错值**）。
          修 = 条件补「别名是指针」（`型定表[全局型定].是否指针标`，C54/C291 已登记）。
       ② **局部**（刀2）: `型序标` 由 `整得` 决定，而 `整得` 经 `容成(名)` 解析 ——
          `typedef S *SP;` 的 `是否构标 = 0`（定义体是 `S *`，非 struct/union）⟹ `容成("SP") = -1`
          ⟹ `型序标` 未设 ⟹ `组八[0]->字段` 的**偏移算错**（实测槽宽度与取值都对，只有 `->` 全错）。
          修 = 补用 C54/C291 已存好的 `型定指构序`。

   覆盖（九格精华）: 全局/局部 × 别名/非别名 × 下标 0/1 + 成员链读。
   旧编译器: 全局格 **rc=0xC0000005**、局部格 **rc=1** ⟹ 以退出码判必红。 */
// @EXPECTED exit:0
// @EXPECTED out:R16 1 1 1 1 7 7 7 7
#include <stdio.h>

typedef struct s1 { struct s1 *x, *y; int v; } S;
typedef S *SP;

static SP gAl[2];            /* 全局【别名】指针数组 */
static S *gPl[2];            /* 全局【非别名】对照 */

int main(void) {
    S a, b;
    SP lAl[2];               /* 局部【别名】指针数组 */
    S *lPl[2];               /* 局部【非别名】对照 */

    a.v = 1; a.x = 0; a.y = &b;
    b.v = 7; b.x = 0; b.y = 0;

    gAl[0] = &a;  gAl[1] = &b;
    gPl[0] = &a;  gPl[1] = &b;
    lAl[0] = &a;  lAl[1] = &b;
    lPl[0] = &a;  lPl[1] = &b;

    printf("R16 %d %d %d %d %d %d %d %d\n",
           gAl[0]->v,          /* 0  全局别名 下标0 : v = 1 ??? 用 比较 形式 见下 */
           gPl[0]->v,
           lAl[0]->v,
           lPl[0]->v,
           gAl[0]->y->v,       /* 4  全局别名 成员链 : 7 */
           lAl[0]->y->v,       /* 5  局部别名 成员链 : 7 */
           gAl[1]->v,          /* 6  全局别名 下标1 : 7 */
           lAl[1]->v);         /* 7  局部别名 下标1 : 7 */
    return 0;
}
