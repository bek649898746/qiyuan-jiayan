# -*- coding: utf-8 -*-
"""recover_qcc_from_jy.py - reverse-transform qcc_work.jy back to qcc_x86.c.

qcc_work.jy was generated by c_to_jy.py from the (strict UTF-8) qcc_x86.c at
23:41 on 2026-08-30.  c_to_jy.py only swaps English C keywords for their 甲言
equivalents at code-identifier positions; comments, string literals and char
literals pass through verbatim.  The reverse map (ZH2EN) is unambiguous
(verified: no two English keywords map to the same 甲言 word), so reversing
the transform recovers the original C source byte-for-byte (in UTF-8).

Usage:
    python scripts/recover_qcc_from_jy.py              # write srclib/qcc_x86.c
    python scripts/recover_qcc_from_jy.py --to TMP     # write to TMP, don't touch srclib
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import c_to_jy

sys.stdout.reconfigure(encoding='utf-8')

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'srclib_jiayan' / 'qcc_work.jy'

ZH2EN = {v: k for k, v in c_to_jy.EN2ZH.items()}


def _id_start(c):
    return ('A' <= c <= 'Z') or ('a' <= c <= 'z') or c == '_' or ord(c) >= 0x80


def _id_char(c):
    return _id_start(c) or ('0' <= c <= '9')


def reverse_translate(s):
    """Inverse of c_to_jy.translate(): 甲言 keywords back to English C keywords."""
    n = len(s)
    out = []
    i = 0
    while i < n:
        c = s[i]
        if c == '/' and i + 1 < n and s[i + 1] == '/':
            j = c_to_jy.skip_line_comment(s, i)
            out.append(s[i:j]); i = j; continue
        if c == '/' and i + 1 < n and s[i + 1] == '*':
            j = c_to_jy.skip_block_comment(s, i)
            out.append(s[i:j]); i = j; continue
        if c == '"':
            j = c_to_jy.skip_string(s, i)
            out.append(s[i:j]); i = j; continue
        if c == "'":
            j = c_to_jy.skip_char_literal(s, i)
            out.append(s[i:j]); i = j; continue
        if _id_start(c):
            j = i + 1
            while j < n and _id_char(s[j]):
                j += 1
            word = s[i:j]
            out.append(ZH2EN.get(word, word))
            i = j
            continue
        out.append(c)
        i += 1
    return ''.join(out)


def main():
    raw = SRC.read_bytes()
    # strip BOM if present
    if raw.startswith(b'\xef\xbb\xbf'):
        raw = raw[3:]
    try:
        text = raw.decode('utf-8')
    except UnicodeDecodeError as e:
        print(f'[ERR] {SRC} not strict UTF-8: {e}')
        return 1

    recovered = reverse_translate(text)

    # validation: re-running the forward transform must reproduce qcc_work.jy
    # (comments/strings verbatim, keywords one-to-one).
    forward, stats = c_to_jy.translate(recovered)
    if forward != text:
        print('[ERR] reverse/forward round-trip mismatch - recovery not exact')
        # find first divergence
        for k in range(min(len(forward), len(text))):
            if forward[k] != text[k]:
                print(f'  first diff at char {k}: forward={forward[max(0,k-40):k+40]!r}')
                print(f'                              text={text[max(0,k-40):k+40]!r}')
                break
        return 1
    # NOTE: stats non-empty is EXPECTED here - forward() re-replaces the English
    # keywords we just restored (that is exactly how the round-trip proves exactness).

    to_path = None
    if '--to' in sys.argv:
        to_path = Path(sys.argv[sys.argv.index('--to') + 1])
    else:
        to_path = ROOT / 'srclib' / 'qcc_x86.c'
    to_path.write_bytes(recovered.encode('utf-8'))
    print(f'OK: recovered {len(recovered)} chars -> {to_path}  (round-trip exact)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
