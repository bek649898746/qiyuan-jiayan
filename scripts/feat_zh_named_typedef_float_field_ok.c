/* 锚: 具名 typedef 结构体 `typedef struct X { double re, im; } T;` 的「逗号续行 字段 浮点标记」
   —— C116/R30 (2026-09-19 第 111 站)
   症状: 第 2+ 个 double 字段丢浮点标记 ⟹ 写双精度值报 A9002「双精度 值赋给整型字段 'x.im'」
        (分号分开的形态 `double re; double im;` 正常);
        指针写法 `p->im = 3.5` 更隐蔽 —— **rc=0 但运行值 0.0** (静默错值), 无任何报错。
   根因 (与 C115 的 `实肆` 完全同构): 带标签 typedef 定义体 (D2 路径) 的浮点标记候选 `值肆`
        的声明写在**循环体内** ⟹ 每轮重置 ⟹ 逗号续行第 2+ 字段 `值肆` 恒 0 ⟹ `构域浮` 不调用。
        匿名路径 (D1) 的对应物 `标轮` 早已被 A26 (2026-09-11) 移出循环 ⟹ D1 正常。
   修法: ① `值肆` 移出循环; ② 循环体首行 `若 (词位 <= 0 || 词型表[词位 - 1] != 逗号) 值肆 = 0;`
        (判据 = 输入流位置, 与控制流无关 —— 与 C115 同一套)。
   锚灵敏度 (实测): 旧编译器 79E07905 (= C115) 上报 A9002 编译失败 ⟹ 必红;
        更旧的 F19EBB9D 上还会先报 A9001 (`W` 的逗号续行, C115 修的) ⟹ 双代必红;
        新编译器 `NTF 3.5 2.5 7.5` rc=0; gcc 逐值同。
   覆盖形态: ① 具名 typedef 逗号续行第 2 字段 ② 指针写 (静默错值形态) ③ 两层 (D1 + D2 复合)。
   ⚠️ 刻意不含 `const double` 前缀形态 —— 那是**另一个既有缺陷** (本轮实测 O/R 用例仍 0.0, 已挂账),
      混入会让本锚失去专一性。 */
#include <stdio.h>

typedef struct Cx { double re, im; } T;   /* 具名 typedef: D2 路径 (逗号续行) */
typedef struct { T a, b; } W;             /* 匿名 typedef + 逗号: D1 路径 (C115 修) */

int main(void) {
    int r = 0;
    T t; t.re = 1.5; t.im = 3.5;          /* ① 逗号续行第 2 字段 */
    T u; T *p = &u; p->im = 2.5;          /* ② 指针写 (C114 上静默 0.0) */
    W w; w.b.im = 7.5;                    /* ③ 两层复合 */

    if (t.im != 3.5) r |= 1;
    if (p->im != 2.5) r |= 2;
    if (w.b.im != 7.5) r |= 4;

    printf("NTF %.1f %.1f %.1f\n", t.im, p->im, w.b.im);
    return r;
}
