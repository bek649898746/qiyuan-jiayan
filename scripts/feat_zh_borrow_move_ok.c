// @EXPECTED out:一=7
// @EXPECTED out:二=7
// @EXPECTED out:三=56
// @EXPECTED exit:0
#include <stdio.h>

/* 族2 #31 借用迁移 (borrow move) · 别名链传播 —— 正例 (2026-10-02 第 443 站):
   借用的引用经 【别名链 r2=r1】 与 【返回值 返 p】 两条路 迁移 出函数后 仍 是 x 的活别名 —
   经 r2 写 x 再读 x 得新值。判据一开一关:
     一 = *r2      (传播后 经 r2 读)          → 7
     二 = *别名(r2)(返回值 迁移后 读)          → 7
     三 = 一 + 二 + x  (经 r2 写 x 后 读 x)     → 7 + 7 + 42 = 56
   若 别名链/返回值迁移 断裂 (r2 非 x 活别名) 则 x 仍为 7 ⟹ 三 = 21 (区分性: 常数/桩 无法给出 56)。
   本体: 借检采 L7510 采集 r2=r1 传播事件 · L7594 复制 r1 活跃绑定给 r2。
   负例面 (传播后 写 被借用变量 且 传播目标 写后仍用 → A3001) 见 feat_zh_borrow_move_neg.c */
int *别名(int *p) { return p; }   /* 借用经返回值迁移 (elision 规则2: 单引用入参 → 返回同域) */

int main(void) {
    int x = 7;
    int *r1, *r2, *r3;
    int 一, 二, 三;
    借用 x;
    r1 = &x;                 /* 绑定 r1→x (先声明后赋值 = 型10 赋值节点, 绑定登记) */
    r2 = r1;                 /* 别名链传播: r2 ← r1 的活跃绑定(x) */
    一 = *r2;                /* → 7 */
    r3 = 别名(r2);           /* 借用经返回值迁移 → 同域, 合法 */
    二 = *r3;                /* → 7 */
    放还 x;
    *r2 = 42;                /* 经别名链写 x (写 *p 只读 p, 放还后 合法) */
    三 = 一 + 二 + x;        /* → 56 (若 r2 非 x 活别名 则 21) */
    printf("一=%d 二=%d 三=%d\n", 一, 二, 三);
    return 0;
}
