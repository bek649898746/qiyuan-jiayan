/* A71-续6 (2026-09-15): 显式转型后的「无符号性」判定 —— `(整数)<无符号 变量>` 应 有符号。
   病灶: `表达式是否无符号(节点)` 对 节点_变量 **直接查变量声明**; 而 甲言的转型「不换节点 只打标记」
         ⟹ `(整数)b` 的节点 仍 是 b 的变量节点, `节无符号[]` 已被转型清成 0, 但函数不看它
         ⟹ 比较走「无符号 小于置位」⟹ `整数 a=-1; 无符号 b=1; a < (整数)b` 得 假 (应 真);
         除法同样受累。对照: (长整)b 正常 / 经变量中转 正常 / 无符号 字符 正常。
   根治: 节点_变量 分支最前加 「显式转型过 (暂合 标记) → 返 节无符号[]」——
         与上方 首甲二/号汇一/节无符号 三条转型标记优先的既有风格一致。
   本锚钉: 转型后比较 / 除法 / 双重转型 / 小无符号提升, 全部与 gcc 逐字节一致。 */
#include <stdio.h>

int main(void) {
    int a = -1;
    unsigned b = 1;
    int m = -120;
    unsigned char uc = 200;

    printf("A=%d B=%d C=%d D=%d E=%d\n",
           a < (int)b,          /* 转型后有符号: -1 < 1 = 真 */
           (unsigned)a > b,     /* 转型后无符号: 0xFFFFFFFF > 1 = 真 */
           m / (int)b,          /* 有符号除法: -120 */
           a < (int)(unsigned)uc, /* 双重转型: -1 < 200 = 真 */
           (int)uc > a);        /* 200 > -1 = 真 */
    return 0;
}
/* @EXPECTED out:A=1 B=1 C=-120 D=1 E=1 */
