#include <stdio.h>
#include <string.h>

int main(void) {
    char c = 3, d[2] = {4,5};
    int  e = 1, f[2][2] = {{4,5},{6,7}};
    int  g[2] = {1,2}, h[2] = {3,4};
    int  p[2][2] = {{1,2},{3,4}}, q[2][2] = {{5,6},{7,8}}, r[2][2];
    int  i, j, k;

    printf("A=%d%d%d ", c, d[0], d[1]);
    printf("B=%d%d%d ", e, f[0][1], f[1][0]);
    printf("C=%d%d ", g[1], h[1]);

    for (i = 0; i < 2; i++)
        for (j = 0; j < 2; j++) {
            r[i][j] = 0;
            for (k = 0; k < 2; k++) r[i][j] += p[i][k] * q[k][j];
        }
    printf("D=%d %d %d %d\n", r[0][0], r[0][1], r[1][0], r[1][1]);
    return 0;
}
