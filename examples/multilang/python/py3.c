/* 0x01 常量N | 0x02 取槽N | 0x03 存槽N | 0x04加 0x05减 0x06乘 0x07除
   0x08 跳绝对 | 0x09 假则跳(弹栈) | 0x10 print
   0x20 <  0x21 >  0x22 ==  0x23 !=  0x24 <=  0x25 >=   (压 0/1)
   0xFF halt */
